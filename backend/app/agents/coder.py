        files = {}

        if project_type == "ml":
            files = self._get_ml_project_files(project_name, is_correction)
        elif project_type == "web":
            files = self._get_web_project_files(project_name, is_correction)
        elif project_type == "data_analysis":
            files = self._get_data_analysis_project_files(project_name, is_correction)
        else:
            files = self._get_general_project_files(project_name, is_correction)

        return files

